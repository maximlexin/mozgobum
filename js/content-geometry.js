// Геометрия, 7 класс (по программе учебника Атанасяна): начальные сведения, треугольники,
// параллельные прямые, соотношения между сторонами и углами треугольника.
// Часть генераторов общая с алгеброй — берём из MB.geoShared (content-math.js).
(() => {
  const { int, pick } = MB.R;
  const ch = MB.choice;
  const { angles, triangle, parallel, triExists, geoStatic, geoTf, angleSort } = MB.geoShared;
  const tf = (q, a, ex) => ({ type: 'tf', q, a, ex });
  const num = (q, a, ex) => ({ type: 'input', q, a: String(a), ex });

  // ---------- Начальные сведения ----------
  const segments = () => {
    const v = int(0, 2), x = int(2, 30), y = int(2, 30);
    if (v === 0) return num(`Точка C лежит на отрезке AB. AC = ${x} см, CB = ${y} см. Найди AB (см).`, x + y, `AB = AC + CB = ${x} + ${y} = ${x + y} см.`);
    if (v === 1) return num(`Точка C лежит на отрезке AB. AB = ${x + y} см, AC = ${x} см. Найди CB (см).`, y, `CB = AB − AC = ${x + y} − ${x} = ${y} см.`);
    return num(`Точка M — середина отрезка AB, AM = ${x} см. Найди AB (см).`, 2 * x, `Середина делит отрезок пополам: AB = 2 · ${x} = ${2 * x} см.`);
  };

  const angleParts = () => {
    const v = int(0, 2), a = int(10, 80), b = int(10, 80);
    if (v === 0) return num(`Луч OC проходит между сторонами угла AOB. ∠AOC = ${a}°, ∠COB = ${b}°. Найди ∠AOB.`, a + b, `∠AOB = ∠AOC + ∠COB = ${a + b}°.`);
    if (v === 1) return num(`Луч OC — биссектриса угла AOB, ∠AOB = ${2 * a}°. Найди ∠AOC.`, a, `Биссектриса делит угол пополам: ${2 * a} : 2 = ${a}°.`);
    return num(`Луч OC — биссектриса угла AOB, ∠AOC = ${a}°. Найди ∠AOB.`, 2 * a, `∠AOB = 2 · ${a} = ${2 * a}°.`);
  };

  const basicsStatic = [
    ch('Сколько прямых можно провести через две точки?', 'одну', ['две', 'бесконечно много', 'ни одной']),
    ch('Часть прямой, ограниченная двумя точками, —…', 'отрезок', ['луч', 'угол', 'прямая']),
    ch('Часть прямой, ограниченная с одной стороны, —…', 'луч', ['отрезок', 'угол', 'ломаная']),
    ch('Чему равен развёрнутый угол?', '180°', ['90°', '360°', '0°']),
    ch('Угол 90° называют…', 'прямым', ['острым', 'тупым', 'развёрнутым']),
    ch('Луч, делящий угол пополам, —…', 'биссектриса', ['медиана', 'высота', 'хорда']),
    tf('Две прямые могут пересекаться в двух точках.', false, 'Две различные прямые пересекаются не более чем в одной точке.'),
    tf('Перпендикулярные прямые при пересечении образуют четыре прямых угла.', true),
    { type: 'sort', q: 'Разложи фигуры', groups: ['Бесконечные', 'Имеют конечную длину'],
      items: [['прямая', 0], ['луч', 0], ['отрезок', 1], ['сторона треугольника', 1]], ex: 'Прямая и луч бесконечны, отрезок имеет длину.' },
  ];

  // ---------- Треугольники ----------
  const triParts = () => {
    const v = int(0, 3), x = int(2, 25);
    if (v === 0) return num(`BM — медиана треугольника ABC, AC = ${2 * x} см. Найди AM (см).`, x, `Медиана делит сторону пополам: ${2 * x} : 2 = ${x} см.`);
    if (v === 1) {
      const b = int(2, 20), side = int(b, b + 20);
      return num(`Периметр равнобедренного треугольника ${2 * side + b} см, основание ${b} см. Найди боковую сторону (см).`, side,
        `Боковые стороны равны: (${2 * side + b} − ${b}) : 2 = ${side} см.`);
    }
    if (v === 2) return num(`Периметр равностороннего треугольника ${3 * x} см. Найди его сторону (см).`, x, `Все стороны равны: ${3 * x} : 3 = ${x} см.`);
    return num(`В равнобедренном треугольнике боковая сторона ${x + 3} см, основание ${x} см. Найди периметр (см).`, 3 * x + 6, `P = ${x + 3} + ${x + 3} + ${x} = ${3 * x + 6} см.`);
  };

  const circleGen = () => {
    const r = int(2, 40);
    return Math.random() < 0.5
      ? num(`Радиус окружности ${r} см. Найди её диаметр (см).`, 2 * r, `Диаметр — два радиуса: 2 · ${r} = ${2 * r} см.`)
      : num(`Диаметр окружности ${2 * r} см. Найди радиус (см).`, r, `Радиус — половина диаметра: ${2 * r} : 2 = ${r} см.`);
  };

  const equality = [
    { type: 'match', q: 'Соедини признак равенства треугольников с его содержанием', pairs: [
      ['1-й признак', 'две стороны и угол между ними'], ['2-й признак', 'сторона и два прилежащих угла'], ['3-й признак', 'три стороны']] },
    ch('У треугольников равны две стороны и угол между ними. По какому признаку они равны?', 'по первому', ['по второму', 'по третьему', 'они не обязательно равны']),
    ch('У треугольников равны сторона и два прилежащих к ней угла. По какому признаку они равны?', 'по второму', ['по первому', 'по третьему', 'они не обязательно равны']),
    ch('У треугольников равны три стороны. По какому признаку они равны?', 'по третьему', ['по первому', 'по второму', 'они не обязательно равны']),
    tf('Если у двух треугольников равны все три угла, треугольники обязательно равны.', false, 'Они могут быть разного размера: маленький и большой треугольник с теми же углами.'),
    tf('В равных треугольниках против равных сторон лежат равные углы.', true),
  ];
  const triLines = [
    ch('В равнобедренном треугольнике медиана, проведённая к основанию, является также…', 'биссектрисой и высотой', ['только высотой', 'хордой', 'стороной']),
    ch('Углы при основании равнобедренного треугольника…', 'равны', ['в сумме 90°', 'всегда острые и разные', 'прямые']),
    tf('В любом треугольнике высота лежит внутри треугольника.', false, 'В тупоугольном треугольнике две высоты лежат вне треугольника.'),
    ...geoStatic.filter(q => q.type !== 'match'),
  ];
  const circle = [
    ch('Отрезок, соединяющий центр окружности с точкой на ней, —…', 'радиус', ['хорда', 'диаметр', 'дуга']),
    ch('Отрезок, соединяющий две точки окружности, —…', 'хорда', ['радиус', 'касательная', 'луч']),
    ch('Самая длинная хорда окружности —…', 'диаметр', ['радиус', 'любая хорда', 'дуга']),
    tf('Все радиусы одной окружности равны.', true),
  ];

  // ---------- Параллельные прямые ----------
  const parStatic = [
    ch('Две прямые на плоскости, которые не пересекаются, называют…', 'параллельными', ['перпендикулярными', 'пересекающимися', 'смежными']),
    ch('Прямые параллельны, если при пересечении секущей…', 'накрест лежащие углы равны', ['односторонние углы равны', 'все углы острые', 'вертикальные углы равны']),
    ch('Через точку вне прямой можно провести параллельную ей прямую…', 'только одну', ['две', 'бесконечно много', 'ни одной'], 'Это аксиома параллельных прямых.'),
    tf('Если две прямые параллельны третьей, то они параллельны между собой.', true),
    tf('Если односторонние углы в сумме дают 180°, прямые параллельны.', true),
    { type: 'sort', q: 'Признаки параллельности: какие углы при параллельных прямых…', groups: ['Равны', 'В сумме 180°'],
      items: [['накрест лежащие', 0], ['соответственные', 0], ['вертикальные', 0], ['односторонние', 1], ['смежные', 1]] },
  ];

  // ---------- Соотношения в треугольнике ----------
  const right30 = () => {
    const a = int(2, 30);
    return Math.random() < 0.5
      ? num(`В прямоугольном треугольнике один острый угол 30°, гипотенуза ${2 * a} см. Найди катет, лежащий против угла 30° (см).`, a, `Катет против угла 30° равен половине гипотенузы: ${2 * a} : 2 = ${a} см.`)
      : num(`В прямоугольном треугольнике катет против угла 30° равен ${a} см. Найди гипотенузу (см).`, 2 * a, `Гипотенуза в два раза больше этого катета: 2 · ${a} = ${2 * a} см.`);
  };

  const relStatic = [
    ch('Против большей стороны треугольника лежит…', 'больший угол', ['меньший угол', 'прямой угол', 'любой угол']),
    ch('Каждая сторона треугольника меньше…', 'суммы двух других сторон', ['разности двух других сторон', 'периметра в 3 раза', 'половины периметра']),
    ...geoTf,
  ];
  const rightStatic = [
    ch('Самая длинная сторона прямоугольного треугольника —…', 'гипотенуза', ['катет', 'медиана', 'высота']),
    ch('Сумма острых углов прямоугольного треугольника равна…', '90°', ['180°', '60°', '45°']),
    tf('В треугольнике может быть два прямых угла.', false, 'Два прямых угла уже дают 180°, на третий ничего не останется.'),
    tf('Катет всегда меньше гипотенузы.', true),
  ];

  const T = {
    basic: `<ul><li>Через две точки проходит <b>одна</b> прямая. Две прямые пересекаются не более чем в одной точке.</li>
      <li><b>Отрезок</b> ограничен двумя точками, <b>луч</b> — одной. Середина делит отрезок пополам.</li>
      <li>Углы: острый &lt; 90°, прямой = 90°, тупой &gt; 90°, развёрнутый = 180°.</li>
      <li><b>Биссектриса</b> делит угол пополам.</li>
      <li><b>Смежные</b> углы в сумме 180°, <b>вертикальные</b> равны. Перпендикулярные прямые образуют прямые углы.</li></ul>`,
    tri: `<div class="rule">1-й признак: две стороны и угол между ними<br>2-й признак: сторона и два прилежащих угла<br>3-й признак: три стороны</div>
      <ul><li><b>Медиана</b> — в середину противолежащей стороны, <b>биссектриса</b> делит угол пополам, <b>высота</b> — перпендикуляр к стороне.</li>
      <li>В <b>равнобедренном</b> треугольнике углы при основании равны, а медиана к основанию — ещё и биссектриса, и высота.</li>
      <li><b>Окружность</b>: радиус, хорда, диаметр = 2 радиуса (самая длинная хорда).</li></ul>`,
    par: `<p><b>Параллельные</b> прямые не пересекаются. При пересечении двух прямых секущей образуются накрест лежащие, соответственные и односторонние углы.</p>
      <div class="rule">Прямые параллельны, если:<br>накрест лежащие углы равны, или<br>соответственные углы равны, или<br>односторонние в сумме 180°</div>
      <p><b>Аксиома:</b> через точку вне прямой проходит только одна прямая, параллельная данной.</p>`,
    rel: `<div class="rule">Сумма углов треугольника = 180°<br>Внешний угол = сумма двух внутренних, не смежных с ним</div>
      <ul><li>Против большей стороны лежит больший угол.</li><li><b>Неравенство треугольника:</b> каждая сторона меньше суммы двух других.</li>
      <li>В прямоугольном треугольнике сумма острых углов 90°, гипотенуза — самая длинная сторона.</li>
      <li>Катет против угла 30° равен половине гипотенузы.</li></ul>`,
  };

  MB.subjects.push({
    id: 'geo', title: 'Геометрия', icon: '📐', color: '#ff4b9b', dark: '#d9337f',
    units: [
      { id: 'g-basic', title: 'Начальные геометрические сведения', desc: 'Прямые, отрезки, лучи, углы', theory: T.basic, lessons: [
        { title: 'Прямая, отрезок, луч', pool: [segments, segments, ...basicsStatic] },
        { title: 'Углы и биссектриса', pool: [angleParts, angleParts, angleSort] },
        { title: 'Смежные и вертикальные углы', pool: [angles] },
      ] },
      { id: 'g-tri', title: 'Треугольники', desc: 'Признаки равенства, медианы, окружность', theory: T.tri, lessons: [
        { title: 'Признаки равенства', pool: equality },
        { title: 'Медиана, биссектриса, высота', pool: [triParts, triParts, ...triLines] },
        { title: 'Окружность', pool: [circleGen, circleGen, ...circle] },
      ] },
      { id: 'g-par', title: 'Параллельные прямые', desc: 'Признаки и свойства параллельных прямых', theory: T.par, lessons: [
        { title: 'Признаки параллельности', pool: parStatic },
        { title: 'Углы при параллельных прямых', pool: [parallel, parallel] },
      ] },
      { id: 'g-rel', title: 'Соотношения в треугольнике', desc: 'Сумма углов, неравенство, прямоугольный треугольник', theory: T.rel, lessons: [
        { title: 'Сумма углов треугольника', pool: [triangle, triangle] },
        { title: 'Неравенство треугольника', pool: [triExists, triExists, ...relStatic] },
        { title: 'Прямоугольный треугольник', pool: [right30, right30, ...rightStatic] },
      ] },
    ],
  });
})();
